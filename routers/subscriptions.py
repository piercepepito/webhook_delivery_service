import secrets

from models import Subscriptions
from db import LocalSession

from schemas import subscriptions
from uuid import UUID

from sqlalchemy import select
from sqlalchemy.exc import NoResultFound, DataError, IntegrityError

from event_catalog import EVENT_TYPES
from routers import exceptions

def create_subscription(payload: subscriptions.SubscriptionCreate) -> dict:
    """
    Creates a subscription and generate a secret key

    The secret key will be generated by the server and will be returned only once.

    Args:
        payload: it should contain the `url`, and the `event types`. Both keys are needed.
    Returns:
        dict: contains the response and the secret key
    """
    plain_secret = secrets.token_urlsafe(32)

    new_sub=Subscriptions(
        url=str(payload.url),
        event_types=payload.event_types,
        secret=plain_secret 
    )

    with LocalSession() as session:
        session.add(new_sub)
        session.commit()

        session.refresh(new_sub)

    return new_sub

def get_subscription(subscription_id: UUID) -> Subscriptions:
    """
    Get the subscription row using id

    args:
    subscription_id: id used to filter out and capture the data

    returns:
    - an ORM SubscriptionRead Object
    """
    with LocalSession() as session:
        stmt = select(Subscriptions).where(
            Subscriptions.id == subscription_id)

        try:
            result = session.execute(stmt)
            subscription = result.scalar_one()
        except DataError as e:
            raise ValueError(f"Improper UUID format")
        except NoResultFound as e:
            raise ValueError("No Id found from input")
        
    return subscription

def get_subscription_url(type: str) -> list[Subscriptions]:
    """part of @app.post /v1/events. Used to get the url from the type in events table. Mainly for fan out.
    Args:
        type: the event type present under the event_catalogs.py file
    Returns
        A list of all desintation urls that the data should be sent
    """
    with LocalSession() as session:
        stmt = select(Subscriptions).where(
            Subscriptions.event_types.any(type),
            Subscriptions.active == True
        )

        result = session.execute(stmt)
        subscription_data = result.scalars().all()

        if not subscription_data:    
            raise ValueError("Unable to find url destination from given event type")

        return subscription_data

def update_subscription(subscription_id: UUID, 
                        subscription_data: subscriptions.SubscriptionUpdate) -> Subscriptions:    
    with LocalSession() as session:
        try:
            subscription = session.get(Subscriptions, subscription_id)

            if subscription is None:
                raise exceptions.SubscriptionNotFoundError("Subscription not found")
            if subscription_data.event_types:
                 subscription.event_types = subscription_data.event_types
            if subscription_data.url:
                 subscription.url = str(subscription_data.url)
            
            session.commit()
            session.refresh(subscription)
            return subscription
    
        except IntegrityError as e:
            session.rollback() 
            raise